using namespace std;
DEFINE_LOG_LABEL(0xD002DA0, "KernelThreadKillLeakInfo");

KernelThreadKillLeakInfo::KernelThreadKillLeakInfo(ProcesssKillEventParam &eventParam,
    int64_t threadNum, int64_t foreGround, int64_t time, string &msg) : ProcessKillLeakInfo(eventParam)
{
    SetLeakedTime();
    threadNum_ = threadNum;
    detailMsg_ = "Generated by HiviewDFX @OpenHarmony\n";
    detailMsg_ += "LOGGER_MEMCHECK_GERNAL_INFO\n";
    detailMsg_ += "pidNumber : " + std::to_string(pid_) + "\n";
    detailMsg_ += "processName : " + processName_ + "\n";
    detailMsg_ += "killTime : " + leakedTime_ + "\n";
    detailMsg_ += "foreGround : ";
    detailMsg_ += (foreGround == 0 ? "no" : "yes");
    detailMsg_ += "\nkillReason : " + killReason_ + "\n";
    detailMsg_ += "ThreadCount : " + std::to_string(threadNum_) + "\n";
    detailMsg_ += "\n";
    detailMsg_ += msg;
}

void KernelThreadKillLeakInfo::SysEventReport()
{
    string version = GetApplicationVersion();
    HiSysEventWrite(HiSysEvent::Domain::RELIABILITY, "THREAD_LEAK", HiSysEvent::EventType::FAULT,
        "PID", pid_,
        "MODULE", processName_.empty() ? "/" : processName_,
        "VERSION", version.empty() ? "/" : version,
        "HAPPEN_TIME", leakedTime_,
        "FIRST_FRAME", "THREAD_QUICK_LEAK",
        "SECOND_FRAME", "OVER_LIMIT",
        "FINGERPRINT", DfrUtil::GetInstance().CalcFingerPrint(
            processName_ + version + eventName_ + "THREAD_QUICK_LEAK, OVER_LIMIT", 0),
        "LOG_PATH", GetFilePath(),
        "FOCUS_MODE", DfrUtil::GetInstance().GetFocusMode(),
        "FOREGROUND", (adj_ == 0 ? "yes" : "no"),
        "APP_RUNNING_ID", appRunningId_,
        "SUMMARY", GetDetailMsg());
}

void KernelThreadKillLeakInfo::AppEventReport()
{
    string version = GetApplicationVersion();
    AppEventHandler::ResourceOverLimitInfo rolInfo;
    rolInfo.pid = pid_;
    rolInfo.uid = uid_;
    rolInfo.bundleName = processName_;
    rolInfo.bundleVersion = version.empty() ? "/" : version;
    std::vector<std::string> logPath;
    logPath.push_back("\"" + GetFilePath() + "\"");
    rolInfo.logPath = logPath;
    rolInfo.appRunningUniqueId = appRunningId_;
    rolInfo.resourceType = "thread";
    rolInfo.threadNum = static_cast<uint32_t>(threadNum_);
    rolInfo.level = "kill";
    bool ret = DfrUtil::GetInstance().PostAppEvent(rolInfo);
    if (!ret) {
        HIVIEW_LOGE("post resource limit event failed");
    } else {
        HIVIEW_LOGI("post resource limit event success");
    }
}

string KernelThreadKillLeakInfo::GetFilePath()
{
    return string(THREAD_LEAK_PATH) + "/" + GetFileName();
}

string KernelThreadKillLeakInfo::GetFileName()
{
    string logName = "threadleak-" + processName_ + "-" + to_string(pid_) + "-log-" + leakedTime_ + ".txt";
    return logName;
}

bool KernelThreadKillLeakInfo::IsDumpMessage()
{
    std::ofstream fout;
    FileParams fileParams;
    fileParams.procName = GetProcessName();
    fileParams.fileName = GetFileName();
    fileParams.logPath = GetFilePath();
    fileParams.foutMode = ios::out | ios::app;
    OldLogCleaner::GetInstance().CreateFile(fileParams, fout);
    if (!fout.is_open()) {
        HIVIEW_LOGE("FAILED TO OPEN FILE: %{public}s", fileParams.logPath.c_str());
        return false;
    }
    fout << GetDetailMsg() << std::endl;
    fout.close();
    return false;
}

