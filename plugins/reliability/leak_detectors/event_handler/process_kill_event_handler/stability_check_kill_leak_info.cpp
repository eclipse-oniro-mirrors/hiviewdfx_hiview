void StabilityCheckKillLeakInfo::DumpGeneralInfo(ofstream &fout)
{
    fout << endl;
    fout << "Generated by HiviewDFX @OpenHarmony" << endl;
    fout << "LOGGER_MEMCHECK_GERNAL_INFO" << endl;
    fout << "\tpidNumber: " << GetPid() << endl;
    fout << "\tprocessName: " << GetProcessName() << endl;
    fout << "\tkillTime: " << leakedTime_ << endl;
    fout << "\tDmaMemory: " << dmaKB_ << " KB" << endl;
    fout << "\tGpuMemory: " << gpuKB_ << " KB" << endl;
    fout << "\tRssMemory: " << rssKB_ << " KB" << endl;
    fout << "\tMaxMemType: " << maxMemTypeStr_ << endl;
    fout << "\tkillReason: " << GetKillReason() << endl;
    fout << endl;
}

void StabilityCheckKillLeakInfo::DumpIoctlData(ofstream &fout)
{
    DumpGeneralInfo(fout);
    string ioctlData = DfrUtil::GetInstance().SendLeakCmdInfo(pid_, CMD_GET_MEM_DETAIL_INFO, infoType_);
    if (!ioctlData.empty()) {
        fout << "*****************************" << endl;
        fout << "LOGGER_MEMCHECK_PROC_INFO" << endl;
        fout << ioctlData << endl;
        fout << "************ endl ************" << endl;
    } else {
        HIVIEW_LOGW("SendLeakCmdInfo returned empty data");
    }
}
