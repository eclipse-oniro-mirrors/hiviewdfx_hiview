DEFINE_LOG_LABEL(0xD002DA0, "StabilityCheckKillLeakInfo");

namespace {
constexpr const char *STR_DMAKB = "dmaKB is: ";
constexpr const char *STR_GPUKB = "gpuKB is: ";
constexpr const char *STR_RSSKB = "rssKB is: ";
constexpr const char *STR_SWAPRSSKB = "swapRssKB:";
struct MemTypeEntry {
    int64_t kbValue;
    uint32_t infoType;
    const char *leakType;
    const char *maxMemTypeStr;
};
} // namespace

StabilityCheckKillLeakInfo::StabilityCheckKillLeakInfo(const ProcesssKillEventParam &eventParam)
    : ProcessKillLeakInfo(eventParam)
{
    ParseInnerMsg(eventParam.innerMsg);
    DetermineMaxMemType();
}

void StabilityCheckKillLeakInfo::ParseInnerMsg(const string &innerMsg)
{
    if (innerMsg.empty()) {
        HIVIEW_LOGW("innerMsg is empty");
        return;
    }
    DfrUtil &dfrUtil = DfrUtil::GetInstance();
    dmaKB_ = static_cast<int64_t>(dfrUtil.GetDegital(innerMsg, STR_DMAKB, ","));
    gpuKB_ = static_cast<int64_t>(dfrUtil.GetDegital(innerMsg, STR_GPUKB, ","));
    int rssOnlyKB = static_cast<int>(dfrUtil.GetDegital(innerMsg, STR_RSSKB, ","));
    int swapRssKB = static_cast<int>(dfrUtil.GetDegital(innerMsg, STR_SWAPRSSKB, ","));
    rssKB_ = rssOnlyKB + swapRssKB;
}

void StabilityCheckKillLeakInfo::DetermineMaxMemType()
{
    MemTypeEntry entries[] = {
        { dmaKB_, STA_DMA_BUFFER_READ_DETAIL, "ION_LEAK", "DMA" },
        { gpuKB_, STA_GPU_BUFFER_READ_DETAIL, "GPU_LEAK", "GPU" },
        { rssKB_, STA_SMAPS_BUFFER_READ_DETAIL, "RSS_LEAK", "RSS" },
    };

    int maxIdx = 0;
    for (int i = 1; i < static_cast<int>(sizeof(entries) / sizeof(entries[0])); i++) {
        if (entries[i].kbValue >= entries[maxIdx].kbValue) {
            maxIdx = i;
        }
    }

    infoType_ = entries[maxIdx].infoType;
    leakType_ = entries[maxIdx].leakType;
    maxMemTypeStr_ = entries[maxIdx].maxMemTypeStr;

    HIVIEW_LOGI("DetermineMaxMemType: %{public}s, leakType=%{public}s",
        maxMemTypeStr_.c_str(), leakType_.c_str());
}

string StabilityCheckKillLeakInfo::GetFileName()
{
    return "/memleak-stabilitycheck-" + processName_ + "-" + to_string(pid_) + "-" + leakedTime_ + ".txt";
}

void StabilityCheckKillLeakInfo::SysEventReport()
{
    string version = GetApplicationVersion();
    HiSysEventWrite(HiSysEvent::Domain::RELIABILITY, "MEMORY_LEAK", HiSysEvent::EventType::FAULT,
        "PID", pid_,
        "UID", uid_,
        "HAPPEN_TIME", leakedTime_,
        "FIRST_FRAME", "STABILITY_CHECK_KILL",
        "SECOND_FRAME", "OVER_LIMIT",
        "THIRD_FRAME", leakType_,
        "MODULE", processName_,
        "VERSION", version.empty() ? "/" : version,
        "LOG_PATH", GetFilePath() + GetFileName(),
        "APP_RUNNING_ID", appRunningId_,
        "FINGERPRINT",
        DfrUtil::GetInstance().CalcFingerPrint(processName_ + version + eventName_ +
                                               "STABILITY_CHECK_KILL, OVER_LIMIT", 0));
}

